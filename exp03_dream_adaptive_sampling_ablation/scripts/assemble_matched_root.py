#!/usr/bin/env python3
"""Complete a matched experiment root by importing the adaptive arm.

The matched run only regenerates the fixed arm, because the adaptive arm of
`outputs/v2` was already greedy: re-running it would burn ~17 GPU-hours to
reproduce identical records. This copies those method directories in so the
matched root is a self-contained experiment that every existing tool
(`summarize_results.py`, `check_run.sh`, the report scripts) reads unmodified.

The import is refused unless the source metadata agrees with the destination's
fixed arm on every setting that would make the two non-comparable: sampling,
seed, candidate cap, canvas length, microbatch, model and timing repeats. That
check is the whole point of the script -- copying is the easy part.
"""
from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

# Settings that must agree for a paired comparison to mean anything. Sampling is
# the one this run exists to fix; the rest guard against importing across a
# configuration change the way outputs/v1 differed from outputs/v2.
MUST_MATCH = (
    "temperature",
    "confidence_metric",
    "top_p",
    "base_seed",
    "max_candidates",
    "continuation_length",
    "verifier_microbatch_size",
    "timing_repeats",
    "model",
    "dtype",
    "prompt_template",
    "eos_policy",
)


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True,
                        help="root holding the adaptive arm to import (outputs/v2)")
    parser.add_argument("--dest", type=Path, required=True,
                        help="matched root holding the freshly generated fixed arm")
    parser.add_argument("--prefix", default="adaptive_",
                        help="method-directory prefix to import")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    imported = 0
    for benchmark_dir in sorted(p for p in args.dest.iterdir() if p.is_dir() and p.name != "comparison"):
        benchmark = benchmark_dir.name
        source_benchmark = args.source / benchmark
        if not source_benchmark.is_dir():
            raise SystemExit(f"No {benchmark} in {args.source}")

        reference_paths = sorted(benchmark_dir.glob("fixed_*/metadata.json"))
        if not reference_paths:
            raise SystemExit(f"{benchmark_dir} has no fixed arm to check against")
        reference = load(reference_paths[0])

        for source_dir in sorted(source_benchmark.glob(f"{args.prefix}*")):
            if not (source_dir / "records.jsonl").is_file():
                continue
            candidate = load(source_dir / "metadata.json")
            mismatched = {
                key: (reference.get(key), candidate.get(key))
                for key in MUST_MATCH
                if reference.get(key) != candidate.get(key)
            }
            if mismatched:
                lines = "\n".join(
                    f"    {key}: fixed arm {have!r} vs {source_dir.name} {want!r}"
                    for key, (have, want) in mismatched.items()
                )
                raise SystemExit(
                    f"Refusing to import {benchmark}/{source_dir.name}: settings differ.\n"
                    f"{lines}\n"
                    "  These arms are not comparable. Regenerate rather than import."
                )
            target = benchmark_dir / source_dir.name
            print(f"  import {benchmark}/{source_dir.name}")
            if not args.dry_run:
                if target.exists():
                    shutil.rmtree(target)
                # records.scored.jsonl is copied along with everything else, so an
                # already-rescored source arrives rescored.
                shutil.copytree(source_dir, target)
            imported += 1

    verb = "would import" if args.dry_run else "imported"
    print(f"{verb} {imported} adaptive method directories from {args.source}")
    if not args.dry_run and imported:
        (args.dest / "IMPORTED_FROM.txt").write_text(
            f"The adaptive_* method directories in this root were copied verbatim from\n"
            f"{args.source.resolve()}\n"
            "after checking that sampling, seed, candidate cap, canvas length, microbatch,\n"
            "model, dtype, prompt template and EOS policy all agree with the fixed arm\n"
            "generated here. The adaptive arm was already greedy, so re-running it would\n"
            "have reproduced identical records.\n"
            "\n"
            "Only the fixed_* directories were generated by this run.\n",
            encoding="utf-8",
        )


if __name__ == "__main__":
    main()
