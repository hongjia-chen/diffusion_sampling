#!/usr/bin/env python3
"""What remasking does to an answer: an exact paired counterfactual.

The cross sweep (`outputs/cross`) ran xadaptive-remask: Dream-only ratio, no
veto, one remasking pass per block. The counterfactual is the same arm with
remasking off (`xadaptive`, no veto) on the same task at the same delta.

Decoding is deterministic (greedy SDAR, CUBLAS_WORKSPACE_CONFIG set, per-task
seed), and the remasking pass consumes randomness only when it actually edits a
token. So a task whose record shows `tokens_changed_by_remask == 0` decodes
identically with remasking off. Only the tasks with at least one edit need
re-running. `verify` checks that claim on a few unchanged tasks too.

    python report/remask_diagnosis.py plan      # subsets + report/data/no_remask/launch.sh
    bash report/data/no_remask/launch.sh        # ~3 h, 3 workers (shared layout)
    python report/remask_diagnosis.py verify    # completeness + the determinism spot-check
    python report/remask_diagnosis.py candidates   # paired outcomes, grouped by what remasking did
    python report/remask_diagnosis.py trace        # traced re-runs of report/examples.json (both arms)
    python report/remask_diagnosis.py check-traces # every traced re-run reproduces its recorded answer
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
HARNESS = PROJECT.parent / "harness"
CROSS = PROJECT / "outputs" / "cross"
DATA = PROJECT / "report" / "data" / "no_remask"
BENCHMARKS = ["gsm8k", "humaneval_plus", "mbpp_plus"]
CANVAS = {"gsm8k": 256, "humaneval_plus": 512, "mbpp_plus": 256}
DELTAS = ["0p10", "0p30", "1p00", "3p00", "10p00"]
# Unchanged tasks re-run as a control: they must reproduce the remask arm's
# completion exactly, or the "unchanged means identical" shortcut is invalid.
CONTROLS_PER_UNIT = 2
# shared layout: Dream alone on GPU0-2, the three SDAR copies share GPU3
WORKERS = [("3", "0"), ("3", "1"), ("3", "2")]


def remask_dir(bench: str, delta: str) -> Path:
    return CROSS / bench / f"xadaptive_remask_noveto_delta_{delta}"


def counterfactual_dir(bench: str, delta: str) -> Path:
    return DATA / "out" / bench / f"xadaptive_noveto_delta_{delta}"


def records(path: Path) -> list[dict]:
    scored = path / "records.scored.jsonl"
    source = scored if scored.exists() else path / "records.jsonl"
    return [json.loads(line) for line in source.open(encoding="utf-8")]


def dataset_rows(bench: str) -> dict[str, dict]:
    path = PROJECT.parent / "data" / "full" / f"{bench}.jsonl"
    return {row["example_id"]: row for row in map(json.loads, path.open(encoding="utf-8"))}


def plan() -> None:
    DATA.mkdir(parents=True, exist_ok=True)
    units = []
    for bench in BENCHMARKS:
        rows = dataset_rows(bench)
        for delta in DELTAS:
            recs = records(remask_dir(bench, delta))
            changed = [r["example_id"] for r in recs if r["tokens_changed_by_remask"] > 0]
            unchanged = [r["example_id"] for r in recs if r["tokens_changed_by_remask"] == 0]
            controls = unchanged[:CONTROLS_PER_UNIT]
            keep = set(changed) | set(controls)
            # sweep order, so the subset's task order matches the sweep's
            ids = [r["example_id"] for r in recs if r["example_id"] in keep]
            subset = DATA / "subsets" / f"{bench}_{delta}.jsonl"
            subset.parent.mkdir(parents=True, exist_ok=True)
            subset.write_text("".join(json.dumps(rows[i]) + "\n" for i in ids), encoding="utf-8")
            cost = sum(r["wall_time_seconds"] for r in recs if r["example_id"] in keep)
            units.append((cost, bench, delta, subset, len(changed), len(controls)))
            print(f"{bench:15s} {delta:6s} changed={len(changed):3d} controls={len(controls)}")
    # longest-processing-time packing over the remask arm's own timings
    units.sort(reverse=True)
    loads = [0.0] * len(WORKERS)
    bins: list[list[tuple]] = [[] for _ in WORKERS]
    for unit in units:
        i = min(range(len(WORKERS)), key=lambda k: loads[k])
        loads[i] += unit[0]
        bins[i].append(unit)
    for i, load in enumerate(loads):
        print(f"worker {i}: ~{load / 3600:.1f} h (upper bound: remask arm timings)")

    lines = [
        "#!/usr/bin/env bash",
        "# Generated by report/remask_diagnosis.py plan. Counterfactual: xadaptive (no",
        "# remask, no veto) on the tasks remasking changed, plus unchanged controls.",
        "# Shared layout -- the timings here are contended and are NOT reported.",
        "set -euo pipefail",
        f'cd "{PROJECT}"',
        'PY="${PYTHON_BIN:-$HOME/miniconda3/envs/diffusion/bin/python}"',
        "export CUBLAS_WORKSPACE_CONFIG=:4096:8",
        f'export PYTHONPATH="{HARNESS}/vendor_env/tf452:{HARNESS}:{PROJECT}"',
        "run_unit() {  # sdar_gpu dream_gpu bench delta subset",
        f'  CUDA_VISIBLE_DEVICES="$1,$2" EXPERIMENT_PHYSICAL_GPU_ID="$1+$2" "$PY" -u {HARNESS}/scripts/run_benchmark.py \\',
        '    --dataset "$5" --output-root "report/data/no_remask/out/$3" \\',
        '    --continuation-length "$6" --verifier-microbatch-size 4 --methods "xadaptive:$4" \\',
        '    --model ../models/SDAR-1.7B-Chat-b64-local --family sdar --block-length 64 \\',
        '    --verifier-model Dream-org/Dream-v0-Instruct-7B --verifier-family dream \\',
        '    --device cuda:0 --verifier-device cuda:1 --dtype bfloat16 --seed 271828 \\',
        '    --timing-repeats 1 --trace-limit 0 --require-lean-logits --max-candidates 64 \\',
        '    --local-files-only --vocab-limit 151665 --adaptive-temperature 0.0 --adaptive-confidence logp',
        "}",
        "pids=()",
    ]
    for (sdar_gpu, dream_gpu), assigned in zip(WORKERS, bins):
        calls = " ; ".join(
            f'run_unit {sdar_gpu} {dream_gpu} {bench} {delta.replace("p", ".")} '
            f'"{subset.relative_to(PROJECT)}" {CANVAS[bench]}'
            for _, bench, delta, subset, _, _ in assigned
        )
        log = f"report/data/no_remask/worker_{dream_gpu}.log"
        lines.append(f'( {calls} ) > "{log}" 2>&1 &')
        lines.append('pids+=("$!")')
    lines += ['failed=0', 'for p in "${pids[@]}"; do wait "$p" || failed=1; done',
              'echo "exit status: $failed"', 'exit "$failed"']
    launch = DATA / "launch.sh"
    launch.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {launch}")


def verify() -> bool:
    ok = True
    for bench in BENCHMARKS:
        for delta in DELTAS:
            with_remask = {r["example_id"]: r for r in records(remask_dir(bench, delta))}
            cf_dir = counterfactual_dir(bench, delta)
            if not (cf_dir / "records.jsonl").exists():
                print(f"MISSING {bench} {delta}")
                ok = False
                continue
            cf = {r["example_id"]: r for r in map(json.loads, (cf_dir / "records.jsonl").open())}
            changed = {k for k, r in with_remask.items() if r["tokens_changed_by_remask"] > 0}
            missing = changed - set(cf)
            controls = [k for k in cf if k not in changed]
            bad_controls = [
                k for k in controls
                if cf[k]["raw_completion"] != with_remask[k]["raw_completion"]
            ]
            identical_changed = sum(
                cf[k]["raw_completion"] == with_remask[k]["raw_completion"] for k in changed & set(cf)
            )
            status = "ok" if not missing and not bad_controls else "FAIL"
            ok &= status == "ok"
            print(f"{status:4s} {bench:15s} {delta:6s} changed={len(changed):3d} rerun={len(changed & set(cf)):3d} "
                  f"controls={len(controls)} controls-identical={len(controls) - len(bad_controls)} "
                  f"changed-but-same-text={identical_changed}")
    return ok


TRACED = PROJECT / "report" / "data" / "traced"
EXAMPLES = PROJECT / "report" / "examples.json"
ARMS = {"remask": "xadaptive-remask", "no_remask": "xadaptive"}


def paired(bench: str, delta: str) -> list[dict]:
    """Per task: the remask arm's record and the counterfactual's (same object if unchanged)."""
    with_remask = records(remask_dir(bench, delta))
    cf_dir = counterfactual_dir(bench, delta)
    cf = {r["example_id"]: r for r in records(cf_dir)} if (cf_dir / "records.jsonl").exists() else {}
    out = []
    for r in with_remask:
        other = cf.get(r["example_id"]) if r["tokens_changed_by_remask"] else r
        out.append({"id": r["example_id"], "with": r, "without": other})
    return out


def outcome(pair: dict) -> str:
    a, b = pair["with"], pair["without"]
    if b is None:
        return "pending"
    if a is b or a["raw_completion"] == b["raw_completion"]:
        return "same text"
    if bool(a["score"]) and not bool(b["score"]):
        return "fixed"
    if bool(b["score"]) and not bool(a["score"]):
        return "broke"
    shorter = a["output_token_count"] < b["output_token_count"] - 3
    longer = a["output_token_count"] > b["output_token_count"] + 3
    return "changed, same score" + (" (shorter)" if shorter else " (longer)" if longer else "")


def candidates() -> None:
    for bench in BENCHMARKS:
        for delta in DELTAS:
            pairs = paired(bench, delta)
            groups: dict[str, list] = {}
            for pr in pairs:
                groups.setdefault(outcome(pr), []).append(pr)
            summary = {k: len(v) for k, v in sorted(groups.items())}
            print(f"\n{bench} {delta}: {summary}")
            for kind in ("fixed", "broke"):
                for pr in sorted(groups.get(kind, []), key=lambda p: p["with"]["output_token_count"])[:4]:
                    a, b = pr["with"], pr["without"]
                    print(f"  {kind:6s} {pr['id']:18s} tokens with={a['output_token_count']:3d} without={b['output_token_count']:3d} "
                          f"edits={a['tokens_changed_by_remask']} stop={a['stop_token_id']}/{b['stop_token_id']} "
                          f"fail={a.get('failure_type')}/{b.get('failure_type')}")


def trace() -> None:
    """Re-run each chosen example with traces, both arms, same delta."""
    chosen = json.loads(EXAMPLES.read_text())
    groups: dict[tuple, list] = {}
    for ex in chosen:
        groups.setdefault((ex["bench"], ex["delta"]), []).append(ex["id"])
    import subprocess
    env = dict(**__import__("os").environ, CUBLAS_WORKSPACE_CONFIG=":4096:8",
               PYTHONPATH=f"{HARNESS}/vendor_env/tf452:{HARNESS}:{PROJECT}")
    python = str(Path.home() / "miniconda3/envs/diffusion/bin/python")
    jobs = []
    for (bench, delta), ids in sorted(groups.items()):
        rows = dataset_rows(bench)
        order = [r["example_id"] for r in records(remask_dir(bench, delta))]
        ids = [i for i in order if i in set(ids)]
        subset = TRACED / "subsets" / f"{bench}_{delta}.jsonl"
        subset.parent.mkdir(parents=True, exist_ok=True)
        subset.write_text("".join(json.dumps(rows[i]) + "\n" for i in ids), encoding="utf-8")
        for arm, kind in ARMS.items():
            jobs.append((bench, delta, arm, kind, subset, len(ids)))
    # exclusive layout, one job per GPU pair at a time
    pairs = [("0", "1"), ("2", "3")]
    procs = []
    for index, (bench, delta, arm, kind, subset, n) in enumerate(jobs):
        sdar_gpu, dream_gpu = pairs[index % 2]
        cmd = [python, "-u", str(HARNESS / "scripts" / "run_benchmark.py"), "--dataset", str(subset),
               "--output-root", str(TRACED / arm / bench), "--continuation-length", str(CANVAS[bench]),
               "--verifier-microbatch-size", "4", "--methods", f"{kind}:{delta.replace('p', '.')}",
               "--model", "../models/SDAR-1.7B-Chat-b64-local", "--family", "sdar", "--block-length", "64",
               "--verifier-model", "Dream-org/Dream-v0-Instruct-7B", "--verifier-family", "dream",
               "--device", "cuda:0", "--verifier-device", "cuda:1", "--dtype", "bfloat16", "--seed", "271828",
               "--timing-repeats", "1", "--trace-limit", str(n), "--require-lean-logits",
               "--max-candidates", "64", "--local-files-only", "--vocab-limit", "151665",
               "--adaptive-temperature", "0.0", "--adaptive-confidence", "logp", "--overwrite"]
        procs.append((pairs[index % 2], cmd, TRACED / f"log_{arm}_{bench}_{delta}.txt"))
    for pair in pairs:
        mine = [(cmd, log) for p, cmd, log in procs if p == pair]
        script = " ; ".join(
            f"CUDA_VISIBLE_DEVICES={pair[0]},{pair[1]} " + " ".join(f"'{c}'" for c in cmd) + f" > '{log}' 2>&1"
            for cmd, log in mine)
        subprocess.Popen(["bash", "-c", script], cwd=PROJECT, env=env)
    print(f"started {len(jobs)} traced runs on {len(pairs)} GPU pairs")


def check_traces() -> bool:
    ok = True
    for ex in json.loads(EXAMPLES.read_text()):
        bench, delta, eid = ex["bench"], ex["delta"], ex["id"]
        pr = next(p for p in paired(bench, delta) if p["id"] == eid)
        for arm, recorded in (("remask", pr["with"]), ("no_remask", pr["without"])):
            label = ("xadaptive_remask_noveto_delta_" if arm == "remask" else "xadaptive_noveto_delta_") + delta
            path = TRACED / arm / bench / label / "records.jsonl"
            got = next((r for r in map(json.loads, path.open()) if r["example_id"] == eid), None) if path.exists() else None
            same = got is not None and got["raw_completion"] == recorded["raw_completion"]
            ok &= same
            print(f"{'ok  ' if same else 'FAIL'} {bench:15s} {delta:6s} {eid:18s} {arm}")
    return ok


if __name__ == "__main__":
    command = sys.argv[1] if len(sys.argv) > 1 else "plan"
    if command == "plan":
        plan()
    elif command == "verify":
        raise SystemExit(0 if verify() else 1)
    elif command == "candidates":
        candidates()
    elif command == "trace":
        trace()
    elif command == "check-traces":
        raise SystemExit(0 if check_traces() else 1)
    else:
        raise SystemExit(f"unknown command {command}")
